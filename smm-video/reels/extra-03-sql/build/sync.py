s = open('narration.md', encoding='utf-8').read()
def R(a, b):
    global s
    if a not in s: print('MISS', a[:70])
    s = s.replace(a, b, 1)
# матни овоз ← матни субтитр (тағйироти муаллиф)
i = s.index('## Матн барои ElevenLabs'); j = s.index('## Код дар видео')
v = s[i:j]
v = v.replace('Пойгоҳи маълумот!', 'Базаи маълумот!')
v = v.replace('Ҷадвали дуюм — харидҳо. Дар он ном навишта намешавад, танҳо рақами харидор. Агар ном иваз шавад, онро танҳо дар як ҷой ислоҳ мекунем.', 'Ҷадвали дуюм — харидҳо. Дар он ном навишта намешавад, танҳо рақами харидор — мисли чек. Агар ном иваз шавад, онро танҳо дар як ҷой ислоҳ мекунем. Ҷадвалҳо бо рақам ба ҳам пайваст мешаванд.')
v = v.replace('Пойгоҳи маълумот баробари ҷадвалҳо плюс рақамҳои пайвасткунанда.', 'Базаи маълумот баробари ҷадвалҳо плюс рақамҳои пайвасткунанда.')
v = v.replace('Видеои пурраи дарсро дар Ютюб тамошо кунед — силка дар описанияи профил!\n\n', '')
v = v.replace('Дарси оянда — намуди зоҳирии барнома: эйч ти эм эл ва си эс эс. Обуна шавед, то аз ҷаҳони барномасозӣ бехабар намонед!\n\n', '')
s = s[:i] + v + s[j:]
R('| Охир | Корти YouTube + профил (пайванд) → «Дарси оянда: HTML ва CSS» |', '| Охир | Ролик бо санҷиш тамом мешавад (бе корти YouTube ва бе «дарси оянда» — тибқи матни муаллиф) |')
open('narration.md', 'w', encoding='utf-8').write(s)
